#include <chess/magic.hpp>

#include <algorithm>
#include <array>
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string_view>

namespace {

void print_magic_array(const char* name, const std::array<std::uint64_t, 64>& magics) {
    std::printf("inline constexpr std::array<std::uint64_t, 64> %s = {\n", name);
    for (int sq = 0; sq < 64; ++sq) {
        if (sq % 4 == 0) std::printf("    ");
        std::printf("0x%016llxULL", static_cast<unsigned long long>(magics[sq]));
        if (sq < 63) std::printf(",");
        std::printf((sq % 4 == 3) ? "\n" : " ");
    }
    std::printf("};\n");
}

}  // namespace

int main(int argc, char** argv) {
    bool check_only = false;
    std::uint64_t seed = 0x9E3779B97F4A7C15ULL;

    for (int i = 1; i < argc; ++i) {
        const std::string_view arg(argv[i]);
        if (arg == "--check") {
            check_only = true;
        } else if (arg == "--seed" && i + 1 < argc) {
            seed = static_cast<std::uint64_t>(std::strtoull(argv[++i], nullptr, 0));
        } else {
            std::fprintf(stderr, "usage: %s [--check] [--seed <u64>]\n", argv[0]);
            return 2;
        }
    }

    const auto t0 = std::chrono::steady_clock::now();

    std::array<std::uint64_t, 64> rook_magics{};
    std::array<std::uint64_t, 64> bishop_magics{};
    std::size_t rook_entries = 0;
    std::size_t bishop_entries = 0;
    std::size_t rook_collisions = 0;
    std::size_t bishop_collisions = 0;
    int rook_pop_sum = 0;
    int bishop_pop_sum = 0;

    for (chess::Square sq = 0; sq < 64; ++sq) {
        const chess::Bitboard rmask = chess::rook_relevancy_mask(sq);
        const chess::Bitboard bmask = chess::bishop_relevancy_mask(sq);
        if (rmask == 0 || bmask == 0) {
            std::fprintf(stderr,
                         "magic_gen: relevancy masks are unimplemented (square %u returned 0).\n",
                         static_cast<unsigned>(sq));
            return 1;
        }

        rook_entries += std::size_t{1} << chess::popcount(rmask);
        bishop_entries += std::size_t{1} << chess::popcount(bmask);

        const std::uint64_t rmagic = chess::find_magic_number(sq, false, seed);
        std::size_t rcoll = 0;
        if (rmagic == 0 || !chess::verify_magic(sq, false, rmagic, &rcoll)) {
            std::fprintf(stderr, "magic_gen: failed to find/verify rook magic for square %u.\n",
                         static_cast<unsigned>(sq));
            return 1;
        }
        rook_magics[sq] = rmagic;
        rook_collisions += rcoll;
        rook_pop_sum += std::popcount(rmagic);

        const std::uint64_t bmagic = chess::find_magic_number(sq, true, seed);
        std::size_t bcoll = 0;
        if (bmagic == 0 || !chess::verify_magic(sq, true, bmagic, &bcoll)) {
            std::fprintf(stderr, "magic_gen: failed to find/verify bishop magic for square %u.\n",
                         static_cast<unsigned>(sq));
            return 1;
        }
        bishop_magics[sq] = bmagic;
        bishop_collisions += bcoll;
        bishop_pop_sum += std::popcount(bmagic);
    }

    const auto elapsed_us = std::chrono::duration_cast<std::chrono::microseconds>(
                                std::chrono::steady_clock::now() - t0)
                                .count();
    const double elapsed_ms = static_cast<double>(elapsed_us) / 1000.0;

    std::fprintf(stderr,
                 "magic_gen: 128 magics verified in %.2f ms (seed=0x%016llx)\n"
                 "  rook:   %zu entries, %zu constructive collisions, avg %.2f bits/magic\n"
                 "  bishop: %zu entries, %zu constructive collisions, avg %.2f bits/magic\n",
                 elapsed_ms, static_cast<unsigned long long>(seed),
                 rook_entries, rook_collisions, static_cast<double>(rook_pop_sum) / 64.0,
                 bishop_entries, bishop_collisions, static_cast<double>(bishop_pop_sum) / 64.0);

    if (!check_only) {
        std::printf("// Generated by magic_gen (seed=0x%016llx)\n",
                    static_cast<unsigned long long>(seed));
        std::printf("#pragma once\n\n#include <array>\n#include <cstdint>\n\n");
        std::printf("namespace chess::generated {\n\n");
        print_magic_array("ROOK_MAGICS", rook_magics);
        std::printf("\n");
        print_magic_array("BISHOP_MAGICS", bishop_magics);
        std::printf("\n}  // namespace chess::generated\n");
    }

    return 0;
}
